function translateDOM() {
  document.documentElement.lang = currentLang;
  document.documentElement.dir = ROOZ_LANGS[currentLang][2];
  document.querySelectorAll("h1,h2,p,button,a,small,span").forEach((el) => {
    if (el.children.length) return;
    const k = exact[el.textContent.trim()];
    if (k) el.textContent = L(k);
  });
  const x = document.querySelector("#adv-title");
  if (x) x.placeholder = L("reminderTitle");
  addLanguageSelect();
}
function addLanguageSelect() {
  if (document.querySelector("#language-select")) return;
  const host =
    document.querySelector("header") || document.querySelector(".start");
  if (!host) return;
  const s = document.createElement("select");
  s.id = "language-select";
  s.setAttribute("aria-label", "Language");
  Object.entries(ROOZ_LANGS).forEach(([c, v]) =>
    s.add(new Option(v[0], c, c === currentLang, c === currentLang)),
  );
  s.onchange = () => {
    localStorage.setItem("rg-lang", s.value);
    location.reload();
  };
  host.appendChild(s);
}
new MutationObserver(translateDOM).observe(document.documentElement, {
  childList: true,
  subtree: true,
});
document.addEventListener("DOMContentLoaded", translateDOM);
